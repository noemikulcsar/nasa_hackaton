// Types shared by the backend packages and tools.

export type RegionId = 'head' | 'chest' | 'pelvis' | 'arms' | 'hands' | 'legs' | 'feet';
export type Activity = 'sleep' | 'rest' | 'work' | 'exercise';
export type Status = 'ok' | 'check' | 'urgent' | 'nodata';

export type SkillId = 'eva' | 'robotics' | 'electrical' | 'thermal' | 'lifeSupport' | 'mechanical' | 'medical';

export interface CrewMember {
  id: string;
  name: string;
  role: string;
  roleShort: string;
  isMedicalOfficer: boolean;
  photo: string;
  osdrSubject: string; // Inspiration4 subject whose real lab tests are attributed to this profile
  sex: 'M' | 'F';
  age: number;
  bio: string;
  dateOfBirth: string;
  bloodType: string;
  mission: { name: string; orbit: string; module: string; missionDay: number; durationDays: number };
  /** The crew member's latest free-text self-assessment */
  feeling: string;
  skills: Record<SkillId, number>; // 0–3
  eva: { certified: boolean; hours: number; count: number };
}

export interface Author {
  id: string;
  name: string;
  kind: 'crew' | 'sensor' | 'system';
}

interface Base {
  id: string;
  ts: number;
  astronautId: string;
  author: Author;
  /** true = generated by the simulator or the demo scenario, not a real measurement */
  simulated: boolean;
}

/** Reading from the vital-sign sensor. `bpm` is the heart rate; the other signals are optional. */
export type HrReading = Base & {
  type: 'hr_reading'; bpm: number; activity: Activity; manual?: boolean;
  spo2?: number; systolic?: number; diastolic?: number; bodyTemp?: number; respiratoryRate?: number;
};
export type DailyLog = Base & {
  type: 'daily_log';
  date: string; // YYYY-MM-DD
  sleepHours: number;
  fatigue: number; // 1–10, reported by the crew member
  exerciseMinutes: number;
  sleepEfficiency?: number; // %
  stress?: number; // 0–10, autoevaluare
};
export type SymptomEvent = Base & { type: 'symptom'; label: string; region: RegionId; note?: string; incidentId?: string };
export type ObservationEvent = Base & { type: 'observation'; text: string; region?: RegionId; incidentId?: string };
export type IncidentOpened = Base & {
  type: 'incident_opened';
  incidentId: string;
  title: string;
  region: RegionId;
  urgency: 'urgent' | 'standard';
  scenario: boolean;
};
export type IncidentClosed = Base & { type: 'incident_closed'; incidentId: string; note?: string };
export type CmoRequested = Base & { type: 'cmo_requested'; incidentId?: string; message: string };
export type CmoAcknowledged = Base & { type: 'cmo_acknowledged'; incidentId?: string; requestId: string };
export type ProtocolOpened = Base & { type: 'protocol_opened'; protocolId: string; version: string; incidentId?: string };

export type HealthEvent =
  | HrReading
  | DailyLog
  | SymptomEvent
  | ObservationEvent
  | IncidentOpened
  | IncidentClosed
  | CmoRequested
  | CmoAcknowledged
  | ProtocolOpened;

export type EventType = HealthEvent['type'];

/** Periodic assessments (bone density, muscle, fluids, radiation, lung, psych). */
export type AssessmentDomain = 'bone' | 'muscle' | 'fluids' | 'radiation' | 'lung' | 'psych';
export type AssessmentEvent = Base & { type: 'assessment'; domain: AssessmentDomain; missionDay: number; values: Record<string, number | string> };
/** Team assigned to a station repair. */
export type RepairAssigned = Base & {
  type: 'repair_assigned'; componentId: string; taskTitle: string;
  team: { role: string; roleLabel: string; crewId: string; name: string }[];
};
/** Every event in the store. The AI assistant receives only `HealthEvent`. */
/** A crew member entered a critical state (raised automatically by the health engine). */
export type CriticalAlertRaised = Base & {
  type: 'critical_alert'; alertId: string; key: string; condition: string; rule: string; region: RegionId; metric?: string;
};
/** The critical state is no longer present. */
export type CriticalAlertResolved = Base & { type: 'alert_resolved'; alertId: string };
/** A crew member confirmed they have seen the alert. */
export type CriticalAlertAcknowledged = Base & { type: 'alert_acknowledged'; alertId: string };
/** Checked again some time after the acknowledgement: still critical, so the alert is raised again. */
export type CriticalAlertRepeated = Base & { type: 'alert_repeated'; alertId: string; afterMs: number };

export type StoredEvent = HealthEvent | AssessmentEvent | RepairAssigned | CriticalAlertRaised | CriticalAlertResolved | CriticalAlertAcknowledged | CriticalAlertRepeated;
export const HEALTH_EVENT_TYPES = new Set<string>(['hr_reading', 'daily_log', 'symptom', 'observation', 'incident_opened', 'incident_closed', 'cmo_requested', 'cmo_acknowledged', 'protocol_opened']);
export const isHealthEvent = (e: StoredEvent): e is HealthEvent => HEALTH_EVENT_TYPES.has(e.type);

export interface Stats {
  mean: number;
  sd: number;
  n: number;
}

export interface Reason {
  status: Status;
  rule: string; // rule identifier, e.g. R-HR-PERSONAL-DEVIATION
  title: string;
  detail: string;
  source: string;
  ts?: number;
}

export interface RegionState {
  status: Status;
  reasons: Reason[];
}

export interface Incident {
  id: string;
  astronautId: string;
  title: string;
  region: RegionId;
  urgency: 'urgent' | 'standard';
  scenario: boolean;
  openedAt: number;
  openedBy: Author;
  closedAt?: number;
  closedBy?: Author;
}

// --- Lab tests (real OSDR data) ---
export interface LabPoint {
  tp: string;
  value: number | null;
  min: number | null;
  max: number | null;
}
export interface LabAnalyte {
  key: string;
  name: string;
  unit: string;
  region: RegionId;
  system: string;
  panel: string;
  hasRange: boolean;
}
export interface LabTimepoint {
  id: string;
  phase: 'pre' | 'post';
  days: number;
  label: string;
}
export interface LabsData {
  source: { repository: string; study: string; mission: string; files: string[]; url: string; note: string };
  timepoints: LabTimepoint[];
  analytes: LabAnalyte[];
  subjects: Record<string, { sex: string; results: Record<string, LabPoint[]> }>;
}

// --- Protocoale ---
export interface ProtocolSection {
  id: string;
  heading: string;
  body: string;
}
export interface Protocol {
  id: string;
  title: string;
  version: string;
  date: string;
  source: string;
  status: 'demo-fictiv' | 'aprobat-misiune';
  approval: { approvedForMission: boolean; approvedBy?: string; approvalDate?: string; reference?: string; note?: string };
  regions: string[];
  keywords: string[];
  summary: string;
  sections: ProtocolSection[];
  /** Text about medicines or doses: allowed ONLY if approval.approvedForMission === true; shown exactly as approved. */
  medication?: { approvedText: string } | null;
}

// --- Asistent ---
export interface AssistantSource {
  id: string; // D1, P1, T1…
  kind: 'data' | 'protocol' | 'timeline' | 'lab';
  label: string;
  detail: string;
  protocolId?: string;
  sectionId?: string;
}
export interface AssistantStep { tool: string; label: string; args: Record<string, unknown> }
export interface AssistantResponse {
  mode: 'agent' | 'local';
  steps?: AssistantStep[];
  provider?: string;
  model?: string;
  answer: string;
  sources: AssistantSource[];
  refused?: boolean;
  /** true = answer given by the safety filter, before the AI model */
  guard?: boolean;
  notice?: string;
}

export interface AiStatus {
  configured: boolean;
  provider: string; // eticheta furnizorului
  model: string;
  reason?: string;
  hint?: string;
  offline: boolean;
}
export interface DemoState {
  sensorsOnline: Record<string, boolean>;
  aiAvailable: boolean;
  ai: AiStatus;
  /** Demo emergencies in progress, by crew member */
  emergencies?: Record<string, string>;
}

export interface Bootstrap {
  serverTime: number;
  meta: { seededAt: number; missionStart: number; missionName: string };
  crew: CrewMember[];
  labs: LabsData;
  protocols: Protocol[];
  rejectedProtocols: { file: string; reason: string }[];
  events: HealthEvent[];
  demo: DemoState;
  config: { hrStaleMs: number; simIntervalMs: number };
}
